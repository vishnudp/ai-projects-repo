from dataclasses import dataclass, field

from app.collectors.base import BaseCollector
from app.collectors.factory import create_collector_from_source
from app.ingestion.base import RawDocument
from app.sdmx.dataflow_filter import DataflowFilter


@dataclass
class CandidateResult:
    """
    Represents a filtered collection candidate.

    Keeps the original document together with the
    intelligence generated by the source-specific
    filtering stage.
    """

    document: RawDocument

    score: float = 0.0

    terms: list[str] = field(
        default_factory=list
    )

    sectors: list[str] = field(
        default_factory=list
    )

    countries: list[str] = field(
        default_factory=list
    )

    reasons: list[str] = field(
        default_factory=list
    )


@dataclass
class CollectionResult:
    """
    Result of a collection operation.

    Collection only.

    Normalization, metadata extraction,
    deduplication and persistence are handled
    by downstream ingestion stages.
    """

    source_id: str

    collector_type: str

    # -------------------------------------------------
    # Collection metrics
    # -------------------------------------------------

    discovered: int = 0

    candidates: int = 0

    selected: int = 0

    retrieved: int = 0

    duration_ms: float = 0.0

    # -------------------------------------------------
    # Documents
    # -------------------------------------------------

    documents: list[RawDocument] = field(
        default_factory=list
    )

    candidate_documents: list[RawDocument] = field(
        default_factory=list
    )

    # -------------------------------------------------
    # Filter intelligence
    # -------------------------------------------------

    candidate_results: list[CandidateResult] = field(
        default_factory=list
    )

    # -------------------------------------------------
    # Errors
    # -------------------------------------------------

    errors: list[str] = field(
        default_factory=list
    )


class CollectionController:
    """
    Orchestrates source collection.

    Source Registry
        ↓
    Collector Factory
        ↓
    Collector
        ↓
    RawDocument[]
        ↓
    Source-specific filtering
        ↓
    CandidateResult[]
    """

    def collect(
        self,
        source_id: str,
    ) -> CollectionResult:

        collector: BaseCollector = (
            create_collector_from_source(
                source_id
            )
        )

        collector_type = type(
            collector
        ).__name__

        # -------------------------------------------------
        # Collection
        # -------------------------------------------------

        try:

            documents = collector.collect()

        except Exception as exc:

            return CollectionResult(
                source_id=source_id,
                collector_type=collector_type,
                errors=[
                    f"{type(exc).__name__}: {exc}"
                ],
            )

        # -------------------------------------------------
        # Validate collector response
        # -------------------------------------------------

        if not isinstance(
            documents,
            list,
        ):

            raise TypeError(
                "Collector must return "
                "list[RawDocument]"
            )

        for document in documents:

            if not isinstance(
                document,
                RawDocument,
            ):

                raise TypeError(
                    "Collector returned an "
                    "invalid document type: "
                    f"{type(document).__name__}"
                )

        discovered_count = len(
            documents
        )

        # -------------------------------------------------
        # Default behavior
        # -------------------------------------------------

        candidate_documents = documents

        candidate_results = [
            CandidateResult(
                document=document
            )
            for document in documents
        ]

        # -------------------------------------------------
        # SDMX dataflow filtering
        # -------------------------------------------------

        if self._is_sdmx_dataflow_collection(
            documents
        ):

            (
                candidate_documents,
                candidate_results,
            ) = self._filter_sdmx_dataflows(
                collector=collector,
                documents=documents,
            )

        # -------------------------------------------------
        # Result
        # -------------------------------------------------

        return CollectionResult(
            source_id=source_id,

            collector_type=collector_type,

            discovered=discovered_count,

            candidates=len(
                candidate_documents
            ),

            selected=0,

            retrieved=0,

            documents=documents,

            candidate_documents=(
                candidate_documents
            ),

            candidate_results=(
                candidate_results
            ),
        )

    # =====================================================
    # SDMX Detection
    # =====================================================

    @staticmethod
    def _is_sdmx_dataflow_collection(
        documents: list[RawDocument],
    ) -> bool:

        if not documents:
            return False

        return all(
            (
                document.metadata
                or {}
            ).get(
                "artifact_type"
            )
            == "sdmx_dataflow"
            for document in documents
        )

    # =====================================================
    # SDMX Filtering
    # =====================================================

    @staticmethod
    def _filter_sdmx_dataflows(
        collector: BaseCollector,
        documents: list[RawDocument],
    ) -> tuple[
        list[RawDocument],
        list[CandidateResult],
    ]:

        collector_config = getattr(
            collector,
            "config",
            {},
        ) or {}

        collection_config = (
            collector_config.get(
                "collection",
                {},
            )
        )

        filter_config = (
            collection_config.get(
                "dataflow_filter",
                {},
            )
        )

        dataflow_filter = DataflowFilter(
            config=filter_config
        )

        results = dataflow_filter.filter(
            documents=documents
        )

        candidate_documents = []

        candidate_results = []

        for result in results:

            document = result.document

            candidate_documents.append(
                document
            )

            candidate_results.append(
                CandidateResult(
                    document=document,

                    score=float(
                        getattr(
                            result,
                            "score",
                            0.0,
                        )
                    ),

                    terms=list(
                        getattr(
                            result,
                            "terms",
                            [],
                        )
                        or []
                    ),

                    sectors=list(
                        getattr(
                            result,
                            "sectors",
                            [],
                        )
                        or []
                    ),

                    countries=list(
                        getattr(
                            result,
                            "countries",
                            [],
                        )
                        or []
                    ),

                    reasons=list(
                        getattr(
                            result,
                            "reasons",
                            [],
                        )
                        or []
                    ),
                )
            )

        return (
            candidate_documents,
            candidate_results,
        )